export function deriveNepaliMeaningFromEnglish(meaningEn: string, topicLabelNe: string): string {
  const clean = (meaningEn || '').trim();
  const lower = clean.toLowerCase();
  for (const [key, val] of Object.entries(EN_TO_NE_GLOSS_MAP)) {
    if (lower === key) return val;
  }
  for (const [key, val] of Object.entries(EN_TO_NE_GLOSS_MAP)) {
    if (lower.includes(key)) {
      return `${val} (${clean})`;
    }
  }
  return `${topicLabelNe} अर्थ: ${clean}`;
}
