export const HI_PHRASE_MAP: Record<string, string> = {};

const LANG_INDEX: Record<string, number> = {
  ko: 0,
  bn: 1,
  ne: 2,
  ur: 3,
  hi: 4,
  ar: 5,
  zh: 6,
  ja: 7
};

function lookupTranslatedValue(trimmed: string, lang: LanguageCode): string | undefined {
  if (!trimmed || lang === 'en') return undefined;
  const tuple = UI_PHRASE_MAP[trimmed];
  if (!tuple) {
    if (lang === 'hi' && HI_PHRASE_MAP[trimmed]) {
      return HI_PHRASE_MAP[trimmed];
    }
    return undefined;
  }
  const idx = LANG_INDEX[lang];
  if (idx === undefined) return undefined;
  const val = tuple[idx];
  if (val) return val;
  if (lang === 'hi' && tuple[2]) return tuple[2];
  return undefined;
}

export function translatePhrase(text: string, lang: LanguageCode): string {
  if (!text || lang === 'en') return text;
  const trimmed = text.trim();
  const translated = lookupTranslatedValue(trimmed, lang);
  return translated ? text.replace(trimmed, translated) : text;
}

/**
 * GlobalPageTranslator:
 * Automatically translates static text nodes and input placeholders across all routes
 * when the user switches between all 9 supported languages (en, bn, ko, ne, ur, hi, ar, zh, ja),
 * and cleanly restores original English text when switching back.
 */
export const GlobalPageTranslator: React.FC = () => {
  const { language } = useApp();
  const location = useLocation();

  useEffect(() => {
    const processDomTree = () => {
      const root = document.getElementById('root');
      if (!root) return;

      // 1. Translate text nodes that match UI_PHRASE_MAP
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node: Node | null = walker.nextNode();
      while (node) {
        const parent = node.parentElement;
        if (
          parent &&
          parent.tagName !== 'SCRIPT' &&
          parent.tagName !== 'STYLE' &&
          !parent.closest('[data-no-translate="true"]')
        ) {
          const originalText = (node as any).__everykrOrigText ?? node.nodeValue ?? '';
          if ((node as any).__everykrOrigText === undefined && originalText.trim()) {
            const trimmed = originalText.trim();
            if (UI_PHRASE_MAP[trimmed] || HI_PHRASE_MAP[trimmed]) {
              (node as any).__everykrOrigText = originalText;
            }
          }

          const baseText: string | undefined = (node as any).__everykrOrigText;
          if (baseText !== undefined) {
            if (language === 'en') {
              if (node.nodeValue !== baseText) {
                node.nodeValue = baseText;
              }
            } else {
              const trimmed = baseText.trim();
              const translatedVal = lookupTranslatedValue(trimmed, language);
              if (translatedVal) {
                const translated = baseText.replace(trimmed, translatedVal);
                if (node.nodeValue !== translated) {
                  node.nodeValue = translated;
                }
              }
            }
          }
        }
        node = walker.nextNode();
      }

      // 2. Translate input/textarea placeholders that match UI_PHRASE_MAP
      const inputs = root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>(
        'input[placeholder], textarea[placeholder]'
      );
      inputs.forEach((el) => {
        if (el.closest('[data-no-translate="true"]')) return;
        const origPlaceholder =
          (el as any).__everykrOrigPlaceholder ?? el.getAttribute('placeholder') ?? '';
        if ((el as any).__everykrOrigPlaceholder === undefined && origPlaceholder.trim()) {
          const trimmed = origPlaceholder.trim();
          if (UI_PHRASE_MAP[trimmed]) {
            (el as any).__everykrOrigPlaceholder = origPlaceholder;
          }
        }
        const basePlaceholder: string | undefined = (el as any).__everykrOrigPlaceholder;
        if (basePlaceholder !== undefined) {
          if (language === 'en') {
            if (el.getAttribute('placeholder') !== basePlaceholder) {
              el.setAttribute('placeholder', basePlaceholder);
            }
          } else {
            const trimmed = basePlaceholder.trim();
            const translatedVal = lookupTranslatedValue(trimmed, language);
            if (translatedVal) {
              const translated = basePlaceholder.replace(trimmed, translatedVal);
              if (el.getAttribute('placeholder') !== translated) {
                el.setAttribute('placeholder', translated);
              }
            }
          }
        }
      });
    };

    const timer = window.setTimeout(processDomTree, 50);

    // Observe dynamic DOM additions (modals, tabs, async cards) with debounce
    let debounceTimer: number | null = null;
    const rootEl = document.getElementById('root');
    const observer =
      rootEl && typeof MutationObserver !== 'undefined'
        ? new MutationObserver(() => {
            if (debounceTimer !== null) window.clearTimeout(debounceTimer);
            debounceTimer = window.setTimeout(processDomTree, 90);
          })
        : null;

    if (observer && rootEl) {
      observer.observe(rootEl, { childList: true, subtree: true });
    }

    return () => {
      window.clearTimeout(timer);
      if (debounceTimer !== null) window.clearTimeout(debounceTimer);
      observer?.disconnect();
    };
  }, [language, location.pathname]);

  return null;
};
